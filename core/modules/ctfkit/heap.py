"""Heap-challenge helper: detect the menu and scaffold a pwntools exploit.

Most heap pwnables are menu-driven (Allocate / Free / Edit / Show / Exit). This
module scans the binary's strings to guess the menu numbers and the prompts the
program shows, then generates a skeleton with ready `alloc/free/edit/show`
wrappers plus a cheat-sheet of the common techniques (tcache poisoning,
double-free, UAF). Detection is heuristic -- always verify against real output.
"""
import os
import re
import stat

from .elf import DANGEROUS, get_symbols, load_binary
from .ui import C, good, hdr, info, warn

# action -> synonyms seen in menu labels
_ACTIONS = [
    ("alloc", r"\b(alloc|allocate|malloc|calloc|create|add|new|make)\b"),
    ("free", r"\b(free|delete|remove|del|release|drop)\b"),
    ("edit", r"\b(edit|update|modify|write|change|fill|set)\b"),
    ("show", r"\b(show|print|view|read|dump|display|list)\b"),
    ("exit", r"\b(exit|quit|leave|bye)\b"),
]
# "1. Allocate", "2) Free", "[3] Edit", "4 - Show", "5: Exit"
_MENU_LINE = re.compile(r"^\s*[\[(]?\s*(\d{1,2})\s*[\]).:\-]+\s*(.+?)\s*$")


def extract_strings(data, minlen=4):
    out, cur = [], bytearray()
    for b in data:
        if 0x20 <= b < 0x7F:
            cur.append(b)
        else:
            if len(cur) >= minlen:
                out.append(cur.decode("latin-1"))
            cur = bytearray()
    if len(cur) >= minlen:
        out.append(cur.decode("latin-1"))
    return out


def _pick_prompt(strings, patterns):
    """Return the shortest string matching the first pattern that hits."""
    for pat in patterns:
        rx = re.compile(pat, re.IGNORECASE)
        matches = [s for s in strings if rx.search(s) and len(s) <= 40]
        if matches:
            return min(matches, key=len)
    return None


def detect_menu(data):
    """Return a dict describing the detected menu actions and prompts."""
    strings = extract_strings(data)
    actions = {}
    for s in strings:
        m = _MENU_LINE.match(s)
        if not m:
            continue
        num, label = int(m.group(1)), m.group(2).lower()
        for act, pat in _ACTIONS:
            if act not in actions and re.search(pat, label):
                actions[act] = num
                break
    return {
        "actions": actions,
        "choice": _pick_prompt(strings, [r"choice", r"option", r"select",
                                         r"command", r"cmd", r">>", r">", r"menu"]),
        "size": _pick_prompt(strings, [r"size", r"length", r"\blen\b", r"bytes",
                                       r"how many", r"how big"]),
        "index": _pick_prompt(strings, [r"index", r"\bidx\b", r"\bid\b", r"which",
                                        r"slot", r"entry", r"number"]),
        "data": _pick_prompt(strings, [r"content", r"\bdata\b", r"\bname\b",
                                       r"value", r"string", r"message", r"text",
                                       r"input"]),
    }


def looks_like_heap(path):
    """True if the binary imports malloc/free (good heap-chall signal)."""
    try:
        pelf, mini = load_binary(path)
    except ValueError:
        return False
    _, imported = get_symbols(pelf, mini)
    bases = {fn.split("@")[0] for fn in imported}
    return bool({"malloc", "free", "calloc", "realloc"} & bases and "free" in bases)


